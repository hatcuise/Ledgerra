import { expect, test } from '@playwright/test';
const api = process.env.E2E_API_BASE_URL ?? 'http://127.0.0.1:5027';

test('bank CSV profile imports purchases and refunds, then reconciles a statement', async ({ page, request }) => {
  const registration = await request.post(`${api}/api/auth/register`, { data: { login: `books-${Date.now()}`, password: 'P@ssw0rd123!' } });
  expect(registration.ok()).toBeTruthy();
  const auth = await registration.json();
  const headers = { Authorization: `Bearer ${auth.accessToken}` };
  const created = await request.post(`${api}/api/accounts`, { headers, data: { name: 'Browser checking', type: 'Checking', currencyCode: 'USD', openingBalance: 100 } });
  expect(created.ok()).toBeTruthy();
  const account = await created.json();
  await page.addInitScript(payload => localStorage.setItem('ledgerra.auth', JSON.stringify(payload)), auth);
  await page.goto('/imports');
  await page.getByRole('combobox', { name: 'Account', exact: true }).selectOption(account.id);
  await page.getByLabel('Report file').setInputFiles({ name: 'card.csv', mimeType: 'text/csv', buffer: Buffer.from('date,amount,memo,payee,number,tags\n4/10/2026,50,Market purchase,Market,123,household\n4/11/2026,-20,Returned item,Market,124,household\n') });
  await page.getByLabel('Positive amounts mean').selectOption('Expense');
  await page.getByLabel('Negative amounts mean').selectOption('Refund');
  await page.getByRole('combobox', { name: 'Payee column (optional)', exact: true }).selectOption('payee');
  await page.getByRole('combobox', { name: 'Reference column (optional)', exact: true }).selectOption('number');
  await page.getByRole('combobox', { name: 'Tags column (optional)', exact: true }).selectOption('tags');
  await page.getByLabel('Profile name').fill('Browser card profile');
  await page.getByRole('button', { name: 'Save bank profile' }).click();
  await expect(page.getByText('Bank profile saved.')).toBeVisible();
  await page.getByRole('button', { name: 'Analyze report', exact: true }).click();
  await expect(page.getByLabel('Type for csv-1')).toHaveValue('Expense');
  await expect(page.getByLabel('Type for csv-2')).toHaveValue('Refund');
  await expect(page.getByLabel('Payee for csv-1')).toHaveValue('Market');
  await expect(page.getByLabel('Tags for csv-1')).toHaveValue('household');
  await page.getByRole('button', { name: 'Save selected drafts' }).click();
  await expect(page.getByLabel('Type for csv-1')).toHaveCount(0);
  await page.getByRole('link', { name: 'Bookkeeping', exact: true }).first().click();
  await page.getByRole('combobox', { name: 'Account', exact: true }).selectOption(account.id);
  await expect(page.getByText('Opening balance: $100.00 · Current balance: $70.00')).toBeVisible();
  await page.getByLabel('Select Market purchase', { exact: true }).check();
  await page.getByLabel('Select Returned item', { exact: true }).check();
  await page.getByLabel('Statement date').fill('2026-04-30');
  await page.getByLabel('Statement ending balance').fill('70');
  await page.getByRole('button', { name: 'Finish reconciliation' }).click();
  await expect(page.getByText('Statement reconciled.', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Select Market purchase', { exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Reopen statement' }).click();
  await expect(page.getByText('Latest statement reopened.', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Select Market purchase', { exact: true })).toBeEnabled();
});
