import { expect, test } from '@playwright/test';
const api = process.env.E2E_API_BASE_URL ?? 'http://127.0.0.1:5027';
async function setup(request: any) {
  const registration = await request.post(`${api}/api/auth/register`, { data: { login: `ledger-${Date.now()}-${Math.floor(Math.random() * 999)}`, password: 'P@ssw0rd123!' } });
  expect(registration.ok()).toBeTruthy(); const auth = await registration.json(); const headers = { Authorization: `Bearer ${auth.accessToken}` };
  const post = async (path: string, data: any) => { const r = await request.post(`${api}${path}`, { headers, data }); expect(r.ok(), await r.text()).toBeTruthy(); return r.json(); };
  const account = await post('/api/accounts', { name: 'Everyday bank', type: 'Checking', currencyCode: 'USD', openingBalance: 100 });
  const food = await post('/api/categories', { name: 'Everyday food', kind: 'Expense' });
  const home = await post('/api/categories', { name: 'Everyday household', kind: 'Expense' });
  return { auth, headers, account, food, home, post };
}

test('split editor, metadata, save-and-keep, clone and named filters survive reload', async ({ page, request }) => {
  const { auth, headers, account, food, home, post } = await setup(request);
  const payee = await post('/api/bookkeeping/payees', { name: 'Everyday market', defaultCategoryId: food.id });
  await page.addInitScript(payload => localStorage.setItem('ledgerra.auth', JSON.stringify(payload)), auth);
  await page.goto('/transactions');
  await page.getByRole('button', { name: 'Add transaction', exact: true }).click();
  await page.getByRole('combobox', { name: 'Account', exact: true }).selectOption(account.id);
  await page.getByLabel('Amount', { exact: true }).fill('30');
  await page.getByRole('textbox', { name: 'Note', exact: true }).fill('Split shopping');
  await page.getByRole('button', { name: 'Add split', exact: true }).click();
  await page.getByLabel('Split category 1').selectOption(food.id); await page.getByLabel('Split amount 1').fill('10');
  await page.getByLabel('Split category 2').selectOption(home.id); await page.getByLabel('Split amount 2').fill('19');
  await expect(page.getByRole('button', { name: 'Save transaction', exact: true })).toBeDisabled();
  await page.getByLabel('Split amount 2').fill('20');
  await page.getByText('Payee, reference, tags and payment details', { exact: true }).click();
  await page.getByRole('combobox', { name: 'Payee', exact: true }).selectOption(payee.id);
  await page.getByLabel('Reference', { exact: true }).fill('statement-1234');
  await page.getByLabel('Tags (comma separated)').fill('household, groceries');
  await page.getByLabel('Payment method', { exact: true }).fill('Card');
  await page.getByRole('combobox', { name: 'Cleared status', exact: true }).selectOption('Cleared');
  await page.getByLabel('Save and keep details for another transaction').check();
  await page.getByRole('button', { name: 'Save transaction', exact: true }).click();
  await expect(page.getByLabel('Split amount 1')).toHaveValue('10');
  await page.getByRole('textbox', { name: 'Note', exact: true }).fill('Second split shopping');
  await page.getByLabel('Save and keep details for another transaction').uncheck();
  await page.getByRole('button', { name: 'Save transaction', exact: true }).click();
  await expect(page.getByLabel('Transaction Second split shopping', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Transaction Split shopping', { exact: true })).toBeVisible();
  const register = await (await request.get(`${api}/api/bookkeeping/accounts/${account.id}/register`, { headers })).json();
  expect(register.balance).toBe(40); expect(register.entries).toHaveLength(2);
  await page.reload();
  const row = page.getByLabel('Transaction Split shopping', { exact: true });
  await row.getByRole('button', { name: 'Transaction actions for Split shopping', exact: true }).click();
  await page.getByRole('button', { name: 'Edit Split shopping', exact: true }).click();
  await expect(page.getByLabel('Reference', { exact: true })).toHaveValue('statement-1234');
  await expect(page.getByLabel('Split amount 1')).toBeVisible();
  await page.getByRole('textbox', { name: 'Note', exact: true }).fill('Edited split shopping');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  const edited = page.getByLabel('Transaction Edited split shopping', { exact: true });
  await edited.getByRole('button', { name: 'Transaction actions for Edited split shopping', exact: true }).click();
  await page.getByRole('button', { name: 'Duplicate Edited split shopping', exact: true }).click();
  await page.getByText('Payee, reference, tags and payment details', { exact: true }).click();
  await expect(page.getByLabel('Reference', { exact: true })).toHaveValue('');
  await expect(page.getByRole('combobox', { name: 'Cleared status', exact: true })).toHaveValue('Uncleared');
  await expect(page.getByLabel('Split amount 1')).toBeVisible();
  await page.getByRole('textbox', { name: 'Note', exact: true }).fill('Cloned split shopping');
  await page.getByRole('button', { name: 'Save transaction', exact: true }).click();
  await page.getByLabel('Search notes').fill('Cloned split shopping');
  await page.getByLabel('Filter name', { exact: true }).fill('Clone review');
  await page.getByRole('button', { name: 'Save named filter', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Saved filter', exact: true })).not.toHaveValue('');
  await page.reload();
  await expect(page.getByRole('combobox', { name: 'Saved filter', exact: true }).locator('option', { hasText: 'Clone review' })).toHaveCount(1);
  await page.getByRole('button', { name: 'Clear', exact: true }).click();
  await page.getByRole('combobox', { name: 'Saved filter', exact: true }).selectOption({ label: 'Clone review' });
  await expect(page.getByLabel('Search notes')).toHaveValue('Cloned split shopping');
  await expect(page.getByLabel('Transaction Cloned split shopping', { exact: true })).toBeVisible();
});

test('hierarchy and merge repair categories, then existing rules are reviewed before applying', async ({ page, request }) => {
  const { auth, headers, account, food, home, post } = await setup(request);
  const entry = await post('/api/transactions', { accountId: account.id, categoryId: food.id, amount: 10, type: 'Expense', occurredOnUtc: '2026-04-10T12:00:00Z', note: 'Legacy cafe' });
  await page.addInitScript(payload => localStorage.setItem('ledgerra.auth', JSON.stringify(payload)), auth);
  await page.goto('/categories');
  await page.getByText('Category hierarchy and merge', { exact: true }).click();
  await page.getByLabel('Category to organize').selectOption(food.id);
  await page.getByRole('combobox', { name: 'Parent category', exact: true }).selectOption(home.id);
  await page.getByRole('button', { name: 'Save parent category' }).click();
  await expect(page.getByText('Category hierarchy saved.', { exact: true })).toBeVisible();
  await page.getByLabel('Merge into category').selectOption(home.id);
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Merge categories', exact: true }).click();
  await expect(page.getByText('Categories merged.', { exact: true })).toBeVisible();
  const updated = await (await request.get(`${api}/api/transactions/${entry.id}`, { headers })).json(); expect(updated.categoryId).toBe(home.id);
  const target = await post('/api/categories', { name: 'Everyday cafe', kind: 'Expense' });
  await post('/api/import-rules', { name: 'Cafe review', matchField: 'Note', matchOperator: 'Contains', matchValue: 'Legacy cafe', assignCategoryId: target.id, assignTransactionType: 'Expense', conditions: [{ field: 'Account', operator: 'Equals', value: account.id }] });
  await page.goto('/bookkeeping');
  await page.getByRole('button', { name: 'Preview existing transaction rules' }).click();
  await expect(page.getByText('1 proposed changes.', { exact: true })).toBeVisible();
  await page.getByLabel('Apply rule to Legacy cafe', { exact: true }).check();
  await page.getByRole('button', { name: 'Apply selected rule changes' }).click();
  await expect(page.getByText('1 transactions updated.', { exact: true })).toBeVisible();
  const result = await (await request.get(`${api}/api/transactions/${entry.id}`, { headers })).json(); expect(result.categoryId).toBe(target.id); expect(result.amount).toBe(10);
});
